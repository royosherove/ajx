// The console reads trials through these hooks so tests can stand in a
// synthetic loader while a dependency is still being written.
var (
	specLoad = func(path string) (util.M, error) {
		return spec.Load(path, spec.LoadOpts{SkipReadiness: true})
	}
	specHarnessFor = func(sp util.M, name string) (plugin.Harness, error) {
		if sp == nil {
			return plugin.NewHarness(name)
		}
		return spec.HarnessFor(sp, name)
	}
	specAuthFor        = func(sp, cell util.M) (plugin.Auth, error) { return spec.AuthFor(sp, cell, "") }
	specEnvironmentFor = spec.EnvironmentFor
	specRunPlan        = func(sp util.M) ([]spec.PlanItem, error) { return spec.RunPlan(sp, nil) }
)

var (
	stages   = runner.Stages
	terminal = runner.Terminal
)

func isTerminal(status string) bool { return util.Contains(terminal, status) }

// labels and statuses are report_ui.LABELS / STATUSES: name -> (icon, tone).
