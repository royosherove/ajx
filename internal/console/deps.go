func pairs(m map[string][2]string) util.M {
	out := util.M{}
	for k, v := range m {
		out[k] = []any{v[0], v[1]}
	}
	return out
}

// progressReporter lets an adapter say explicitly whether it reports live progress.
type progressReporter interface{ ReportsProgress() bool }

// hasProgress is Python's `type(harness).progress is not base.Harness.progress`:
// whether the adapter declares its own Progress rather than inheriting the
// base one (which reports nothing). Methods promoted from an embedded
// BaseHarness are compiler-generated wrappers; a declared method has a source file.
func hasProgress(h plugin.Harness) bool {
	if h == nil {
		return false
	}
	if p, ok := h.(progressReporter); ok {
		return p.ReportsProgress()
	}
	if _, isBase := h.(*plugin.BaseHarness); isBase {
		return false
	}
	declared := func(t reflect.Type) bool {
		m, ok := t.MethodByName("Progress")
		if !ok {
			return false
		}
		fn := runtime.FuncForPC(m.Func.Pointer())
		if fn == nil {
			return false
		}
		file, _ := fn.FileLine(fn.Entry())
		return file != "" && file != "<autogenerated>"
	}
	t := reflect.TypeOf(h)
	if declared(t) {
		return true
	}
	if t.Kind() == reflect.Pointer && declared(t.Elem()) {
		return true
	}
	return false
}
